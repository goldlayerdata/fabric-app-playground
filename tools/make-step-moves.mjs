// Writes src/step-moves.mjs: where the saved step positions of lessons whose steps were split now point.
// `node tools/make-step-moves.mjs`. Compares src/lesson-list.mjs as it was at FROM (the last version the
// site published before the split) with today's, step by step (see tools/step-moves-lib.mjs).
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { lessons } from '../src/lesson-list.mjs';
import { lessonsAt, movesFor } from './step-moves-lib.mjs';

export const FROM = '676c135';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const moves = movesFor(await lessonsAt(FROM), lessons);
const rows = Object.entries(moves).map(([id, m]) => `  '${id}': [${m.join(', ')}],`);
writeFileSync(
  join(root, 'src', 'step-moves.mjs'),
  `// Generated by tools/make-step-moves.mjs: do not edit by hand. npm run check verifies it.
//
// Some steps were split in two or three (one action per card), so a step position saved in the browser
// before that, or before ${FROM}, points too early. For each lesson that changed: the new position of every old
// one (index = old position: 0 the idea card, 1..n the steps, n + 1 the summary). The app moves saved
// positions once, then sets STEPS_VERSION.
export const STEPS_FROM = '${FROM}';
export const STEPS_VERSION = '2';
export const stepMoves = {
${rows.join('\n')}
};
`,
);
console.log(`src/step-moves.mjs: ${Object.keys(moves).length} lessons`);
for (const [id, m] of Object.entries(moves)) console.log(`  ${id}: ${m.map((n, i) => (n === i ? null : `${i}→${n}`)).filter(Boolean).join(', ')}`);
